export type StatusValue = "completed" | "success" | "warning" | "error" | "undefined"

export type Milestone = {
  year: number
  realized: number
  target?: number
}

export type LinkedLists = {
  opportunityListId?: string
  customerListId?: string
}

export type OKRItem = {
  type: "Objective" | "Key Result"
  level?: 1 | 2
  status: StatusValue
  tags: string[]
  opportunities?: { id: number; name: string; value: number; status: string }[]
  milestones: Milestone[]
  linked?: LinkedLists
}

export type PartnerTeamMember = { initials: string; color: string }

// Lightweight entities for partner-scoped saved lists
export type OpportunityLite = { id: number | string; name: string; customer: string; value: number }
export type OpportunityListLite = {
  id: string
  title: string
  count: number
  totalValue: number
  updated?: string
  items: OpportunityLite[]
}
export type Customer = {
  id: string | number
  name: string
  company?: string
  email?: string
  status: "active" | "inactive" | "pending"
  code?: string
  teamSize: "small" | "medium" | "large" | "enterprise"
  team: { name: string; role: string; avatar?: string }[]
  owner?: string
  partnerCount?: number
  okrs: Record<string, { label?: string; value: string | number; status: string; progress?: number }>
  productInstances?: ProductInstance[]
}
export type CustomerList = {
  id: string
  title: string
  count: number
  updated?: string
  items: Customer[]
}
export type PartnerLists = {
  opportunityLists: OpportunityListLite[]
  customerLists: CustomerList[]
}

export type ProductInstance = {
  productName: string // The product name (e.g., "Life Insurance", "Auto")
  attributes: {
    name?: string // Instance name
    productId?: string
    description?: string
    provider?: string
    contractStartDate?: string
    contractEndDate?: string
    totalValue?: string
    premiumValue?: string
    premiumPercent?: string
    discountPercent?: string
    productCategory?: string
    lifecycleStage?: string
    policyId?: string
    dossierId?: string
    policyholderId?: string
    policyNumber?: string
    contractId?: string
    insurer?: string
    productDomain?: string
    productType?: string
    billingFrequency?: string
    status?: string
    situation?: string
    lastPremiumAmount?: string
  }
}

export type Partner = {
  id: number
  idVnemer: number // Added unique integer ID for each customer
  name: string
  status: "active" | "inactive" | "pending"
  code?: string
  teamSize: "small" | "medium" | "large" | "enterprise"
  team: PartnerTeamMember[]
  owner?: string
  partnerCount?: number // Added partnerCount to mock data
  okrs: Record<string, OKRItem>
  lists?: PartnerLists
  currentProducts?: string[] // Products the customer currently has
  productInstances?: ProductInstance[] // Added detailed product instances with attributes
  desiredProducts?: string // Single recommended product for cross-sell (was array)
  expiringProduct?: string // Product that is expiring soon
  contractEndDate?: string // Contract end date in dd/mm/yyyy format
  email?: string // Added email field for coverage-related smart list
}

// Currency-ish compact formatting with Euro suffix where applicable
export function formatCompactEuro(value: number | string) {
  if (typeof value !== "number") return String(value)
  if (value >= 1000) return `${(value / 1000).toFixed(0)}k €`
  return `${value} €`
}

